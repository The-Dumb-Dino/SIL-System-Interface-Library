# src/sysdep/sdlgpu/shaders/build-shaders.sh: Compile the default shaders
# and write them as C arrays to files included by shader.c:
#     ../shaders-spirv.i  SPIR-V (Vulkan) from default.vert / default.frag
#     ../shaders-dxil.i   DXIL (Direct3D 12, Shader Model 6.0) from default.hlsl
#     ../shaders-dxbc.i   DXBC (Direct3D 12, Shader Model 5.1) from default.hlsl
# The generated files are checked in, so this only needs to be run after
# changing the shader sources.
#
# Compilers: glslc (Vulkan SDK or shaderc) for SPIR-V, dxc (DirectX Shader
# Compiler) for DXIL, fxc (Windows SDK) for DXBC.  They are looked up in
# $GLSLC / $DXC / $FXC, then in the PATH, then in the usual install
# locations.  Without arguments, every output whose compiler is found is
# regenerated (the others are skipped with a warning); with -spirv, -dxil
# and/or -dxbc, only those outputs are built and a missing compiler is an
# error.
#
# Usage:
#     ./build-shaders.sh [-spirv] [-dxil] [-dxbc]

set -e
cd "$(dirname "$0")"

# Keep MSYS from rewriting compiler options like "-Fo" or "/T" as paths.
export MSYS2_ARG_CONV_EXCL='*'

want_spirv=0
want_dxil=0
want_dxbc=0
explicit=0
for arg in "$@"; do
    case "$arg" in
        -spirv) want_spirv=1; explicit=1 ;;
        -dxil)  want_dxil=1;  explicit=1 ;;
        -dxbc)  want_dxbc=1;  explicit=1 ;;
        *)      echo "Usage: $0 [-spirv] [-dxil] [-dxbc]" >&2; exit 1 ;;
    esac
done
if [ $explicit = 0 ]; then
    want_spirv=1; want_dxil=1; want_dxbc=1
fi

# find_tool <variable value> <name> [fallback paths...]
find_tool() {
    if [ -n "$1" ]; then echo "$1"; return; fi
    name=$2; shift 2
    if command -v "$name" >/dev/null 2>&1; then command -v "$name"; return; fi
    for path in "$@"; do
        if [ -x "$path" ]; then echo "$path"; return; fi
    done
}
winsdk_tool() {  # winsdk_tool <name.exe>: newest Windows SDK copy, if any
    ls -d "/c/Program Files (x86)/Windows Kits/10/bin/"10.*/x64/"$1" \
        2>/dev/null | sort -r | head -n 1
}
GLSLC=$(find_tool "$GLSLC" glslc "$HOME/VulkanSDK/1.4.363.1/macOS/bin/glslc")
DXC=$(find_tool "$DXC" dxc "$(winsdk_tool dxc.exe)")
FXC=$(find_tool "$FXC" fxc "$(winsdk_tool fxc.exe)")

check_tool() {  # check_tool <want variable name> <tool path> <tool name>
    eval "want=\$$1"
    if [ "$want" = 1 ] && [ -z "$2" ]; then
        if [ $explicit = 1 ]; then
            echo "$3 not found" >&2; exit 1
        fi
        echo "Warning: $3 not found, skipping its output" >&2
        eval "$1=0"
    fi
}
check_tool want_spirv "$GLSLC" glslc
check_tool want_dxil "$DXC" dxc
check_tool want_dxbc "$FXC" fxc

# Relative path, so that native Windows compilers can use it too.
TMP=$(mktemp -d ./.build-shaders.XXXXXX)
trap 'rm -rf "$TMP"' EXIT

emit_array() {  # emit_array <name> <file>
    printf 'static const uint8_t %s[] = {' "$1"
    od -An -v -tu1 "$2" | tr -s ' \n' ',' | sed 's/^,//; s/,$//'
    printf '};\n'
}

compile_spirv() {  # compile_spirv <stage> <source> <name> [defines...]
    stage=$1; src=$2; name=$3; shift 3
    "$GLSLC" -fshader-stage="$stage" --target-env=vulkan1.0 -O "$@" \
        -o "$TMP/$name.spv" "$src"
    emit_array "$name" "$TMP/$name.spv"
}

compile_dxil() {  # compile_dxil <target> <name> [defines...]
    target=$1; name=$2; shift 2
    "$DXC" -nologo -T "$target" -E main -O3 -Qstrip_reflect "$@" \
        -Fo "$TMP/$name.dxil" default.hlsl >&2
    emit_array "$name" "$TMP/$name.dxil"
}

compile_dxbc() {  # compile_dxbc <target> <name> [defines...]
    target=$1; name=$2; shift 2
    "$FXC" -nologo -T "$target" -E main -O3 -Qstrip_reflect -Qstrip_debug \
        "$@" -Fo "$TMP/$name.dxbc" default.hlsl >&2
    emit_array "$name" "$TMP/$name.dxbc"
}

if [ "$want_spirv" = 1 ]; then
    {
        echo '/* Generated by build-shaders.sh from default.vert / default.frag.'
        echo ' * Do not edit by hand. */'
        for tex in 0 1; do
            for color in 0 1; do
                compile_spirv vert default.vert "spirv_vertex_t${tex}_c${color}" \
                    -DHAS_TEX=$tex -DHAS_COLOR=$color
            done
        done
        compile_spirv frag default.frag spirv_fragment
    } > "$TMP/spirv.i"
    mv "$TMP/spirv.i" ../shaders-spirv.i
    echo "Wrote ../shaders-spirv.i"
fi

# compile_hlsl <format> <vertex target> <fragment target>
compile_hlsl() {
    {
        echo '/* Generated by build-shaders.sh from default.hlsl.'
        echo ' * Do not edit by hand. */'
        for tex in 0 1; do
            for color in 0 1; do
                "compile_$1" "$2" "${1}_vertex_t${tex}_c${color}" \
                    -DVERTEX_SHADER -DHAS_TEX=$tex -DHAS_COLOR=$color
            done
        done
        "compile_$1" "$3" "${1}_fragment" -DFRAGMENT_SHADER
    } > "$TMP/$1.i"
    mv "$TMP/$1.i" "../shaders-$1.i"
    echo "Wrote ../shaders-$1.i"
}

if [ "$want_dxil" = 1 ]; then
    compile_hlsl dxil vs_6_0 ps_6_0
fi
if [ "$want_dxbc" = 1 ]; then
    compile_hlsl dxbc vs_5_1 ps_5_1
fi
